"""
Question 04: Chinese Ambiguity Analysis
中文歧義句分析：他知道這件事不要緊
"""

sentence = "他知道這件事不要緊"

print("=" * 70)
print("中文歧義句分析")
print("=" * 70)
print(f"\n句子：{sentence}")

print("\n" + "=" * 70)
print("【歧義分析】")
print("=" * 70)

print("\n理解方式 1：")
print("斷句：他知道 | 這件事不要緊")
print("意思：他知道【這件事情不重要】")
print("英文：He knows [this matter is not important]")
print()
print("詞性結構：")
print("  他（代詞）+ 知道（動詞）")
print("  這件事（名詞）+ 不（副詞）+ 要緊（形容詞）")

print("\n" + "-" * 70)

print("\n理解方式 2：")
print("斷句：他知道這件事 | 不要緊")
print("意思：他知道這件事情，【沒關係/無所謂】")
print("英文：He knows this matter, [it doesn't matter / no worries]")
print()
print("詞性結構：")
print("  他（代詞）+ 知道（動詞）+ 這件事（名詞，賓語）")
print("  不要緊（形容詞/慣用語，表示安慰或評論）")

print("\n" + "=" * 70)
print("【歧義來源】")
print("=" * 70)
print("""
1. 斷句位置不同：
   - 「知道」後斷句 vs 「這件事」後斷句

2. 「不要緊」的語法角色不同：
   - 修飾「這件事」（不重要的事）
   - 獨立評論/安慰（沒關係、無所謂）

3. 缺少標點符號：
   - 加逗號可消歧：「他知道，這件事不要緊」（意思1）
   - 或：「他知道這件事，不要緊」（意思2）
""")

print("=" * 70)
print("【消除歧義的方法】")
print("=" * 70)
print("""
方法 1：加標點符號
  意思 1：「他知道，這件事不要緊。」
  意思 2：「他知道這件事，不要緊。」

方法 2：改寫句子
  意思 1：「他知道這件事情不重要。」
  意思 2：「他知道這件事，沒關係的。」

方法 3：增加上下文
  意思 1：「他知道這件事不要緊，所以沒有告訴任何人。」
  意思 2：「他知道這件事，不要緊，我們還有時間處理。」
""")

print("=" * 70)
